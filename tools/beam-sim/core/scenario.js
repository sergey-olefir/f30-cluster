'use strict';
// Scenario files of the beam simulator (docs/highbeam/CONTRACT.md §5): load, validate, list, and the page's bundle.
//
//   list()                 -> [ { id, family, name, purpose } ]  (Node: scenarios/*.json; page: the bundle)
//   load(idOrPathOrObject) -> the scenario object (Node reads `framesFile` JSON Lines next to the file)
//   validate(s)            -> [ 'error', ... ]  (empty = valid)
//   node tools/beam-sim/core/scenario.js --bundle     writes ui/scenarios.bundle.js for the page (file:// cannot read JSON)
//   node tools/beam-sim/core/scenario.js --check      validates every file, prints one line each
(function () {
  const isNode = typeof require !== 'undefined' && typeof module !== 'undefined';
  const fs = isNode ? require('fs') : null;
  const path = isNode ? require('path') : null;
  const DIR = isNode ? path.join(__dirname, '..', 'scenarios') : null;
  const FAMILIES = { A: 'empty and baseline', B: 'oncoming', C: 'vehicles ahead', D: 'divided roads', E: 'towns and lit roads',
    F: 'things that fool cameras', G: 'weak road users', H: 'weather and camera faults', I: 'the driver', J: 'dusk, tunnel, speed, stops',
    K: 'flicker and cut-ins', R: 'recorded drives' };
  const KINDS = ['car', 'truck', 'moto', 'bike', 'ped', 'parked'];
  const STALK = ['high_on', 'high_off', 'flash', 'rearm'];

  function files() {
    if (!isNode) return [];
    return fs.readdirSync(DIR).filter((f) => /\.json$/.test(f)).sort();
  }
  function list() {
    if (!isNode) return ((typeof self !== 'undefined' && self.BS_SCENARIOS) || []).map((s) => ({ id: s.id, family: s.family, name: s.name, purpose: s.purpose }));
    return files().map((f) => { const s = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')); return { id: s.id, family: s.family, name: s.name, purpose: s.purpose }; });
  }
  function readJsonl(p) {
    return fs.readFileSync(p, 'utf8').split('\n').filter((l) => l.trim() && l.trim()[0] !== '#').map((l) => JSON.parse(l));
  }
  function load(x) {
    if (x && typeof x === 'object') return x;
    if (!isNode) {
      const all = (typeof self !== 'undefined' && self.BS_SCENARIOS) || [];
      const s = all.filter((a) => a.id === x)[0];
      if (!s) throw new Error('no scenario ' + x);
      return JSON.parse(JSON.stringify(s));
    }
    let p = String(x);
    if (!fs.existsSync(p)) p = path.join(DIR, x + '.json');
    if (!fs.existsSync(p)) throw new Error('no scenario ' + x);
    const s = JSON.parse(fs.readFileSync(p, 'utf8'));
    if (!Array.isArray(s.frames) && s.framesFile) s.frames = readJsonl(path.join(path.dirname(p), s.framesFile));
    return s;
  }
  function validate(s) {
    const e = [];
    if (!s || typeof s !== 'object') return ['not an object'];
    if (s.format !== 'beam-scenario') e.push('format must be "beam-scenario"');
    if (s.version !== 1) e.push('version must be 1');
    if (typeof s.id !== 'string' || !s.id) e.push('id missing');
    const hasWorld = s.world && typeof s.world === 'object';
    const hasFrames = Array.isArray(s.frames) || typeof s.framesFile === 'string';
    if (!hasWorld && !hasFrames) e.push('needs world or frames');
    if (hasWorld && hasFrames) e.push('world and frames are exclusive');
    if (hasWorld) {
      if (!(s.duration_s > 0)) e.push('duration_s must be > 0');
      if (typeof s.purpose !== 'string' || !s.purpose) e.push('purpose missing (one line)');
      if (s.family && !FAMILIES[s.family]) e.push('unknown family ' + s.family);
      const w = s.world;
      (w.users || []).forEach((u, i) => {
        if (KINDS.indexOf(u.kind) < 0) e.push('users[' + i + '].kind ' + u.kind);
        if ([-1, 0, 1].indexOf(u.dir === undefined ? -1 : u.dir) < 0) e.push('users[' + i + '].dir');
      });
      (w.driver || []).forEach((d, i) => { if (STALK.indexOf(d.kind) < 0) e.push('driver[' + i + '].kind ' + d.kind); });
      ((w.road && w.road.segments) || []).forEach((g, i) => { if (!(g.len_m > 0)) e.push('road.segments[' + i + '].len_m'); });
    }
    if (Array.isArray(s.frames)) {
      let lastT = -Infinity;
      s.frames.forEach((f, i) => {
        if (!f || typeof f.t !== 'number') { e.push('frames[' + i + '].t'); return; }
        if (f.t < lastT) e.push('frames[' + i + '].t goes back');
        lastT = f.t;
      });
    }
    (s.driver || []).forEach((d, i) => { if (typeof d.t !== 'number' || ['high_on', 'high_off', 'flash'].indexOf(d.kind) < 0) e.push('driver[' + i + ']'); });
    return e;
  }
  function bundle() {
    const all = files().map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')));
    const out = '// generated by: node tools/beam-sim/core/scenario.js --bundle (do not edit)\nself.BS_SCENARIOS = ' + JSON.stringify(all) + ';\n';
    const p = path.join(__dirname, '..', 'ui', 'scenarios.bundle.js');
    fs.writeFileSync(p, out);
    return { path: p, n: all.length, bytes: out.length };
  }

  const X = { list: list, load: load, validate: validate, bundle: bundle, files: files, FAMILIES: FAMILIES, DIR: DIR };
  if (typeof module !== 'undefined') module.exports = X; else (self.BS = self.BS || {}).scenario = X;

  if (isNode && require.main === module) {
    const a = process.argv.slice(2);
    if (a.indexOf('--bundle') >= 0) { const r = bundle(); console.log('wrote ' + r.path + ' (' + r.n + ' scenarios, ' + r.bytes + ' bytes)'); }
    if (a.indexOf('--check') >= 0) {
      let bad = 0;
      files().forEach((f) => { const s = load(path.join(DIR, f)); const er = validate(s); if (er.length) bad++; console.log((er.length ? 'BAD ' : 'ok  ') + f + (er.length ? '  ' + er.join('; ') : '')); });
      process.exit(bad ? 1 : 0);
    }
  }
})();
