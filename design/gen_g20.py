#!/usr/bin/env python3
"""Generates the "G20 Comfort" layout: the stock G20 Comfort cluster's look, our own drawing (the bench simulation's,
docs/G20SIM-REPORT.md, baked by tools/bake_g20.py into hud/scene/g20_*.json and design/g20_geo.json):
    python3 design/gen_g20.py apps/f30_cluster/hud/layouts
Writes g20_comfort.json. Edit this file, not the JSON.

Four gauges (G20DIAL: the baked static gauge, opaque over BMW's own so its pointer never shows twice; the pointer, its
glow and the rev band live), the rpm label and (car3 J) the stock layout's mode label and gear letter in the tacho's
centre. Everything else is see-through: BMW draws its own digital speed, telltales, bottom row, speed-limit sign,
check-control messages and map round and under them, as with "6WB Dials + G20". Refitted on photos 39 / 40:
docs/CAR3-J-REPORT.md."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
G = json.load(open(os.path.join(HERE, 'g20_geo.json')))
FONTS = os.path.join(HERE, '..', 'apps', 'f30_cluster', 'hud', 'fonts')


def cell(font):
    return json.load(open(os.path.join(FONTS, font + '.json')))['cellHeight']


def text(id, x, base, w, t, font, align, conn, color='fg', asc=0.711, size=None):
    """A text box whose glyphs sit on the baseline `base` (x: the left or the right edge by align)."""
    h = cell(font)
    cy = base - asc * size / 2.0
    x0 = x if align == 'left' else x - w / 2.0 if align == 'center' else x - w
    return {"id": id, "type": "text", "z": 5, "x": int(round(x0)), "y": int(round(cy - h / 2.0)), "w": w, "h": h,
            "text": t, "font": font, "color": color, "align": align, "conn": conn}


def gauge(id, name, rows, conn, **kw):
    x0, y0, x1, y1 = G[name]['box']
    d = {"id": id, "type": "g20dial", "class": "content", "z": 1, "x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0,
         "base": "g20_" + name, "lut": "g20_lut", "rows": rows, "conn": conn}
    d.update(kw)
    return d


B, GL, N, NL = G['bar'], G['glow'], G['needle'], G['numLight']
SH = B['shadow']
# car3 J: the glow is the simulation's angular wedge (sigma in degrees by side, the depth window q0..q1); the numerals
# by the pointer are lit (numLight); the minis' needle is w0 wide at the frame end (the tip) and w1 at its inner end
# (the tail), as the simulation draws it (the port had them swapped)
big = dict(bar=[B['width'], B['width'], B['rim']['offset'], B['rim']['width']], barC=B['rgb'],
           rim=B['rim']['rgb'] + [B['rim']['alpha']], rimHi=B['rim']['hi_alpha'],
           shadow=[SH['alpha'], SH['d0'], SH['lambda'], SH['dmax']], glow=GL['rgb'] + [GL['sigma']],
           glow2=[GL['sigmaLo'], GL['q'][0], GL['q'][1], GL['qIn']], numLight=[NL['gain'], NL['sigma'], NL['q'][0], NL['q'][1]],
           bandLight=G['bandLight'] + [0])
small = dict(mini=True, bar=[N['w1'], N['w0'], 0, 0], barC=N['rgb'], tipC=N['tip_rgb'])
GREY = [172, 160, 163, 255]    # car3 J: the stock print's grey (the dial numerals, km/h, 1/min x1000): 0.68 of the white (39)
MODE = [124, 118, 121, 255]    # car3 J: the mode label's grey (39: 113, 103, 106 against the 0's 254, 222, 229)
W = [
    gauge("speedo", "speedo", [0, 1], 0, measure="speed", min=0, max=260, centre=G['speedoC'], **big),
    gauge("tacho", "tacho", [2, 3], 1, measure="rpm", min=0, max=7000, centre=G['tachoC'],
          band=G['band']['psi'] + [G['band']['width']], bandC=G['band']['rgb'], **big),
    # the minis over the big dials (their boxes overlap)
    gauge("fuel", "fuel", [4, 5], 0, z=2, fill="g20_fuel_fill", signal="fuel", min=0, max=1, **small),
    gauge("oil", "oil", [6, 7], 1, z=2, fill="g20_oil_fill", signal="oil", min=G['oilRange'][0], max=G['oilRange'][1], **small),
    # no digital speed of ours: BMW still draws its own there under a theme (design/overlay assist.digital_speed: under,
    # strong) and the baked speedo leaves that spot see-through, so a copy of ours only doubled it. The rpm labels stay
    # ours: the baked tacho covers BMW's.
    text("rpm1", 1424, 596.5, 110, "1/min", "g20_lab", "left", 2, color=GREY, size=34),
    text("rpm2", 1424, 625.8, 110, "x1000", "g20_lab", "left", 2, color=GREY, size=34),
    # car3 J: the stock layout's mode label and gear letter in the tacho's centre, over the line the baked tacho now
    # carries (photo 39; design/overlay assist.mode_label_centre and gear_centre). While a theme is connected BMW moves
    # them to its bottom row: its label there is covered by the baked tacho, its gear letter is drawn over any theme.
    text("mode1", 1223, 366.6, 200, "{{g20mode1}}", "g20_mode", "left", 2, color=MODE, size=31.5),
    text("mode2", 1223, 394.6, 200, "{{g20mode2}}", "g20_mode", "left", 2, color=MODE, size=31.5),
    text("gear", 1519.5, 395.0, 120, "{{stage}}", "g20_gear", "center", 2, size=105),
]
lay = {"schemaVersion": 2, "name": "G20 Comfort", "packWaste": 8, "theme": "wb_comfort",
       "_about": "The stock G20 Comfort look, generated by design/gen_g20.py: edit that and regenerate.", "widgets": W}
json.dump(lay, open(os.path.join(sys.argv[1], "g20_comfort.json"), "w"), indent=2, ensure_ascii=False)
