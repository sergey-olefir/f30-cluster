#!/usr/bin/env python3
"""Generates the "G20 Comfort" layout: the stock G20 Comfort cluster's look, our own drawing (the bench simulation's,
docs/G20SIM-REPORT.md, baked by tools/bake_g20.py into hud/scene/g20_*.json and design/g20_geo.json):
    python3 design/gen_g20.py apps/f30_cluster/hud/layouts
Writes g20_comfort.json. Edit this file, not the JSON.

Four gauges (G20DIAL: the baked static gauge, opaque over BMW's own so its pointer never shows twice; the pointer, its
glow and the rev band live) and the digital speed. Everything else is see-through: BMW draws its own telltales, bottom
row, speed-limit sign, check-control messages and map round and under them, as with "6WB Dials + G20"."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
G = json.load(open(os.path.join(HERE, 'g20_geo.json')))
FONTS = os.path.join(HERE, '..', 'apps', 'f30_cluster', 'hud', 'fonts')


def cell(font):
    return json.load(open(os.path.join(FONTS, font + '.json')))['cellHeight']


def text(id, x, base, w, t, font, align, conn, color='fg', asc=0.711, size=None):
    """A text box whose glyphs sit on the baseline `base` (x: the left or the right edge by align)."""
    h = cell(font)
    cy = base - asc * size / 2.0
    x0 = x if align == 'left' else x - w
    return {"id": id, "type": "text", "z": 5, "x": int(round(x0)), "y": int(round(cy - h / 2.0)), "w": w, "h": h,
            "text": t, "font": font, "color": color, "align": align, "conn": conn}


def gauge(id, name, rows, conn, **kw):
    x0, y0, x1, y1 = G[name]['box']
    d = {"id": id, "type": "g20dial", "class": "content", "z": 1, "x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0,
         "base": "g20_" + name, "lut": "g20_lut", "rows": rows, "conn": conn}
    d.update(kw)
    return d


B, GL, N = G['bar'], G['glow'], G['needle']
big = dict(bar=[B['width'], B['width'], B['rim']['offset'], B['rim']['width']], barC=B['rgb'],
           rim=B['rim']['rgb'] + [B['rim']['alpha']], glow=GL['rgb'] + [GL['sigma']])
small = dict(mini=True, bar=[N['w0'], N['w1'], 0, 0], barC=N['rgb'], tipC=N['tip_rgb'])
W = [
    gauge("speedo", "speedo", [0, 1], 0, measure="speed", min=0, max=260, centre=G['speedoC'], **big),
    gauge("tacho", "tacho", [2, 3], 1, measure="rpm", min=0, max=7000, centre=G['tachoC'],
          band=G['band']['psi'] + [G['band']['width']], bandC=G['band']['rgb'], **big),
    gauge("fuel", "fuel", [4, 5], 0, signal="fuel", min=0, max=1, **small),
    gauge("oil", "oil", [6, 7], 1, signal="oil", min=G['oilRange'][0], max=G['oilRange'][1], **small),
    # the digital speed and its unit (the bench simulation's boxes, bench/g20/c.js T.speed, T.speedUnit)
    text("speed", 530, 396, 240, "{{speed}}", "g20_spd", "right", 2, size=105),
    text("speed_unit", 539, 393, 80, "km/h", "g20_unit", "left", 2, size=27),
    text("rpm1", 1424, 596.5, 110, "1/min", "g20_lab", "left", 2, size=34),
    text("rpm2", 1424, 625.8, 110, "x1000", "g20_lab", "left", 2, size=34),
]
lay = {"schemaVersion": 2, "name": "G20 Comfort", "packWaste": 8, "theme": "wb_comfort",
       "_about": "The stock G20 Comfort look, generated by design/gen_g20.py: edit that and regenerate.", "widgets": W}
json.dump(lay, open(os.path.join(sys.argv[1], "g20_comfort.json"), "w"), indent=2, ensure_ascii=False)
